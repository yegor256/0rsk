require 'json'
require 'net/http'
require 'uri'

require_relative 'rsk'
require_relative 'urror'

class Rsk::TaskTracker
  GITHUB_API = 'https://api.github.com'

  def initialize(repo, token)
    @repo = repo
    @token = token
  end

  def create(task, http: nil)
    existing = find(task, http: http)
    return existing unless existing.nil?
    uri = URI.parse("#{GITHUB_API}/repos/#{@repo}/issues")
    request = Net::HTTP::Post.new(uri.path)
    request['Authorization'] = "Bearer #{@token}"
    request['Content-Type'] = 'application/json'
    request['User-Agent'] = '0rsk'
    request.body = {
      title: "Task: #{task[:ptext]}",
      body: [
        "Risk: #{task[:ctext]} \u2192 #{task[:rtext]} \u2192 #{task[:etext]}",
        "Plan: #{task[:ptext]}",
        "Schedule: #{task[:schedule]}",
        '',
        "<!-- #{marker(task)} -->",
        '',
        '_(generated by [0rsk](https://www.0rsk.com))_'
      ].join("\n")
    }.to_json
    Integer(JSON.parse(roundtrip(request, uri, http))['number'])
  end

  private

  def find(task, http: nil)
    uri = URI.parse("#{GITHUB_API}/search/issues")
    uri.query = URI.encode_www_form(q: "repo:#{@repo} \"#{marker(task)}\"")
    request = Net::HTTP::Get.new(uri)
    request['Authorization'] = "Bearer #{@token}"
    request['User-Agent'] = '0rsk'
    (JSON.parse(roundtrip(request, uri, http))['items'] || []).first&.fetch('number', nil)
  end

  def roundtrip(request, uri, http)
    (http || the_http(uri)).request(request).tap do |response|
      code = Integer(response.code, 10)
      case code
      when 200..299
        return response.body
      when 401
        raise(Rsk::Urror, "GitHub API: invalid token for #{@repo}")
      when 403
        raise(Rsk::Urror, "GitHub API: rate limited or forbidden for #{@repo}")
      when 404
        raise(Rsk::Urror, "GitHub API: repository #{@repo} not found")
      when 422
        errs = JSON.parse(response.body)['errors']
        raise(Rsk::Urror, "GitHub API: #{errs&.map { |e| e['message'] }&.join(', ') || 'validation error'}")
      else
        raise(Rsk::Urror, "GitHub API error (#{code}): #{response.message}")
      end
    end
  rescue Net::ReadTimeout, Net::OpenTimeout => e
    raise(Rsk::Urror, "GitHub API timeout: #{e.message}")
  rescue SocketError, Errno::ECONNREFUSED => e
    raise(Rsk::Urror, "GitHub API connection failed: #{e.message}")
  end

  def marker(task)
    "0rsk-task-#{task[:id]}"
  end

  def the_http(uri)
    h = Net::HTTP.new(uri.host, uri.port)
    h.use_ssl = true
    h.open_timeout = 10
    h.read_timeout = 10
    h
  end
end
